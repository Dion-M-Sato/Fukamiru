def _load_jawl_predicates() -> tuple[AcademicPredicate, ...]:
    entries: list[AcademicPredicate] = []
    for line in _JAWL_PREDICATE_DATA.splitlines():
        level, lemma, part_of_speech, raw_forms = line.split("\t", 3)
        entries.append(
            AcademicPredicate(
                level=level,
                lemma=lemma,
                part_of_speech=part_of_speech,
                corpus_forms=tuple(
                    dict.fromkeys(
                        form for form in raw_forms.split("|") if form and form not in {"#N", "A"}
                    )
                ),
            )
        )
    return tuple(entries)


