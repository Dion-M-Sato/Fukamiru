def academic_predicate_matches(text: str) -> tuple[dict[str, object], ...]:
    """Return every JAWL predicate-capable lexeme attested in *text*."""

    matches: list[dict[str, object]] = []
    for entry in JAWL_ACADEMIC_PREDICATES:
        forms = tuple(
            form
            for form in sorted(entry.corpus_forms, key=len, reverse=True)
            if form and form in text
        )
        if not forms:
            continue
        matches.append(
            {
                "lemma": entry.lemma,
                "level": entry.level,
                "part_of_speech": entry.part_of_speech,
                "matched_forms": list(forms),
            }
        )
    return tuple(matches)


def academic_modality_matches(text: str) -> tuple[str, ...]:
    return tuple(item for item in ACADEMIC_MODALITY_EXPRESSIONS if item in text)


def discourse_marker_matches(text: str) -> dict[str, list[str]]:
    return {
        relation: [marker for marker in markers if marker in text]
        for relation, markers in DISCOURSE_RELATION_MARKERS.items()
        if any(marker in text for marker in markers)
    }
